// branchResource manages a branch of a dedicated database: a copy that shares
// the parent's credentials but has its own host and database name, useful for
// giving a preview environment a throwaway copy of production data.
//
// A branch has no update route, so every configurable attribute forces
// replacement. When `ttl` is set the server deletes the branch on expiry; a
// refresh after that removes it from state and the next plan recreates it.
type branchResource struct {
	engine  Engine
	clients *common.AppwriteClients
}

type branchResourceModel struct {
	ID         types.String `tfsdk:"id"`
	DatabaseID types.String `tfsdk:"database_id"`
	BranchID   types.String `tfsdk:"branch_id"`
	TTL        types.Int64  `tfsdk:"ttl"`

	BranchName       types.String `tfsdk:"branch_name"`
	Namespace        types.String `tfsdk:"namespace"`
	ExpiresAt        types.Int64  `tfsdk:"expires_at"`
	Host             types.String `tfsdk:"host"`
	Port             types.Int64  `tfsdk:"port"`
	Database         types.String `tfsdk:"database"`
	Username         types.String `tfsdk:"username"`
	Password         types.String `tfsdk:"password"`
	SSL              types.Bool   `tfsdk:"ssl"`
	Engine           types.String `tfsdk:"engine"`
	ConnectionString types.String `tfsdk:"connection_string"`

	ProjectID types.String `tfsdk:"project_id"`
}

// NewBranchResource returns a constructor for the branch resource of one engine.
func NewBranchResource(engine Engine) func() resource.Resource {
	return func() resource.Resource {
		return &branchResource{engine: engine}
	}
}

func (r *branchResource) Metadata(_ context.Context, req resource.MetadataRequest, resp *resource.MetadataResponse) {
	resp.TypeName = fmt.Sprintf("%s_%s_branch", req.ProviderTypeName, r.engine)
}

