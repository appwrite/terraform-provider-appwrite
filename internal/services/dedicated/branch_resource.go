func (r *branchResource) Configure(_ context.Context, req resource.ConfigureRequest, resp *resource.ConfigureResponse) {
	if req.ProviderData == nil {
		return
	}
	clients, ok := req.ProviderData.(*common.AppwriteClients)
	if !ok {
		resp.Diagnostics.AddError(
			"Unexpected Resource Configure Type",
			fmt.Sprintf("Expected *common.AppwriteClients, got: %T", req.ProviderData),
		)
		return
	}
	r.clients = clients
}

func (r *branchResource) Create(ctx context.Context, req resource.CreateRequest, resp *resource.CreateResponse) {
	var plan branchResourceModel
	resp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...)
	if resp.Diagnostics.HasError() {
		return
	}

	projectID, err := common.ResolveProjectID(r.clients, plan.ProjectID)
	if err != nil {
		resp.Diagnostics.AddError("Missing project_id", err.Error())
		return
	}
	api := clientFor(r.clients, r.engine, projectID)
	databaseID := plan.DatabaseID.ValueString()

	if _, err := api.CreateBranch(databaseID, CreateBranchOptions{
		BranchID: optString(plan.BranchID),
		TTL:      optInt(plan.TTL),
	}); err != nil {
		resp.Diagnostics.AddError("Error creating branch", common.FormatError(err))
		return
	}

	// CreateBranch answers with the parent database rather than the branch, and
	// there is no per-branch read route, so the branch's own connection details
	// have to come from the branch list.
	branch, err := r.findBranch(api, databaseID, plan.BranchID)
	if err != nil {
		resp.Diagnostics.AddError("Error reading created branch", err.Error())
		return
	}

	plan.ProjectID = types.StringValue(projectID)
	r.mapToState(branch, &plan)
	resp.Diagnostics.Append(resp.State.Set(ctx, &plan)...)
}

func (r *branchResource) Read(ctx context.Context, req resource.ReadRequest, resp *resource.ReadResponse) {
	var state branchResourceModel
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}

	projectID, err := common.ResolveProjectID(r.clients, state.ProjectID)
	if err != nil {
		resp.Diagnostics.AddError("Missing project_id", err.Error())
		return
	}
	api := clientFor(r.clients, r.engine, projectID)

	list, err := api.ListBranches(state.DatabaseID.ValueString())
	if err != nil {
		// A deleted parent database takes its branches with it.
		if common.IsNotFoundError(err) {
			resp.State.RemoveResource(ctx)
			return
		}
		resp.Diagnostics.AddError("Error listing branches", common.FormatError(err))
		return
	}

	branch := findBranchByID(list, state.BranchID.ValueString())
	if branch == nil {
		// Most likely the TTL expired and the server reclaimed the branch.
		resp.State.RemoveResource(ctx)
		return
	}

	state.ProjectID = types.StringValue(projectID)
	r.mapToState(branch, &state)
	resp.Diagnostics.Append(resp.State.Set(ctx, &state)...)
}

// Update is unreachable: every configurable attribute forces replacement.
func (r *branchResource) Update(ctx context.Context, req resource.UpdateRequest, resp *resource.UpdateResponse) {
	var plan branchResourceModel
	resp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...)
	resp.Diagnostics.Append(resp.State.Set(ctx, &plan)...)
}

func (r *branchResource) Delete(ctx context.Context, req resource.DeleteRequest, resp *resource.DeleteResponse) {
	var state branchResourceModel
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}

	projectID, err := common.ResolveProjectID(r.clients, state.ProjectID)
	if err != nil {
		resp.Diagnostics.AddError("Missing project_id", err.Error())
		return
	}
	api := clientFor(r.clients, r.engine, projectID)

	if err := api.DeleteBranch(state.DatabaseID.ValueString(), state.BranchID.ValueString()); err != nil && !common.IsNotFoundError(err) {
		resp.Diagnostics.AddError("Error deleting branch", common.FormatError(err))
	}
}

func (r *branchResource) ImportState(ctx context.Context, req resource.ImportStateRequest, resp *resource.ImportStateResponse) {
	databaseID, branchID, ok := splitImportID(req.ID)
	if !ok {
		resp.Diagnostics.AddError("Invalid import ID", fmt.Sprintf("Expected format: database_id/branch_id, got: %s", req.ID))
		return
	}
	resp.Diagnostics.Append(resp.State.SetAttribute(ctx, path.Root("database_id"), databaseID)...)
	resp.Diagnostics.Append(resp.State.SetAttribute(ctx, path.Root("branch_id"), branchID)...)
	resp.Diagnostics.Append(resp.State.SetAttribute(ctx, path.Root("id"), branchID2ID(databaseID, branchID))...)
}

// findBranch locates a freshly created branch. When the ID was generated by the
// server the configuration has none to match on, so the branch is identified by
// being the only one the parent did not have before -- which the list makes
// unambiguous only when a branch ID was supplied. Without one, the newest
// branch is taken.
func (r *branchResource) findBranch(api databaseAPI, databaseID string, configuredID types.String) (*models.DedicatedDatabaseBranch, error) {
	list, err := api.ListBranches(databaseID)
	if err != nil {
		return nil, fmt.Errorf("listing branches: %s", common.FormatError(err))
	}

	if !configuredID.IsNull() && !configuredID.IsUnknown() {
		if branch := findBranchByID(list, configuredID.ValueString()); branch != nil {
			return branch, nil
		}
		return nil, fmt.Errorf("branch %q was created but is not in the branch list", configuredID.ValueString())
	}

	// A server-generated ID: the branch that expires last is the one just made,
	// since every branch shares the same TTL policy from creation time.
	var newest *models.DedicatedDatabaseBranch
	for i := range list.Branches {
		if newest == nil || list.Branches[i].ExpiresAt > newest.ExpiresAt {
			newest = &list.Branches[i]
		}
	}
	if newest == nil {
		return nil, fmt.Errorf("branch was created but the branch list is empty")
	}
	return newest, nil
}

func findBranchByID(list *models.DedicatedDatabaseBranchList, branchID string) *models.DedicatedDatabaseBranch {
	for i := range list.Branches {
		if list.Branches[i].BranchId == branchID {
			return &list.Branches[i]
		}
	}
	return nil
}

func branchID2ID(databaseID, branchID string) string {
	return databaseID + "/" + branchID
}

func (r *branchResource) mapToState(branch *models.DedicatedDatabaseBranch, model *branchResourceModel) {
	model.BranchID = types.StringValue(branch.BranchId)
	model.ID = types.StringValue(branchID2ID(model.DatabaseID.ValueString(), branch.BranchId))
	model.BranchName = types.StringValue(branch.BranchName)
	model.Namespace = types.StringValue(branch.Namespace)
	model.ExpiresAt = types.Int64Value(int64(branch.ExpiresAt))
	model.Host = types.StringValue(branch.Host)
	model.Port = types.Int64Value(int64(branch.Port))
	model.Database = types.StringValue(branch.Database)
	model.Username = types.StringValue(branch.Username)
	model.Password = types.StringValue(branch.Password)
	model.SSL = types.BoolValue(branch.Ssl)
	model.Engine = types.StringValue(branch.Engine)
	model.ConnectionString = types.StringValue(branch.ConnectionString)
}
